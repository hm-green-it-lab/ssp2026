# helper/jagent.py
"""
Provision, attach and stop the eBPF jAgent on the SUT host.

The agent must run on the SUT: it loads BPF programs into that kernel and
attaches to that JVM's PID, so it cannot be driven from the controller.

Three provisioning modes, selected by ``jagent.provision``:

``release`` (default)
    Download the published ``linux-x86_64`` tarball on the controller, ship it
    to the SUT and unpack it. Nothing is compiled, so the SUT needs no
    toolchain -- only the shared libraries the binary links. This is the right
    mode for Ubuntu targets and makes runs reproducible against a fixed tag.

``source``
    Ship the working tree from the controller and ``make`` it on the SUT. Use
    this to measure uncommitted changes. The agent cannot be cross-built: its
    userspace part links libbpf/libelf/libcurl and the BPF object needs the
    SUT's kernel headers.

``preinstalled``
    Assume a binary is already at ``jagent.binary``.

Two settings are mandatory at run time:

``JVM_LIB_PATH``
    The ``libjvm.so`` whose USDT probe sites are patched. It must belong to the
    JVM running the SUT, otherwise the probes resolve to nothing.
``OTLP_ENDPOINT``
    Where the OTLP/HTTP exporter posts. The agent refuses to start without it,
    even when nothing is listening.

Both are passed through the environment rather than via the agent's ``.env``:
``env_loader.c`` overlays real environment variables on top of that file, so
neither the release payload nor a developer checkout needs editing.
"""

from __future__ import annotations

import fnmatch
import shlex
import tarfile
import tempfile
import time
from pathlib import Path

import paramiko

from helper.downloads import fetch_release_archive
from helper.ssh import (
    RemoteProcess,
    ensure_dir,
    exists,
    privilege_prefix,
    run,
    upload,
)

BINARY_NAME = "ebpf-jagent"
NOOP_BINARY_NAME = "ebpf-noop-agent"

HERE = Path(__file__).resolve().parent.parent

# Build products are never shipped in `source` mode: the binary is rebuilt on
# the SUT, and the skeleton is regenerated by `bpftool gen skeleton`.
DEFAULT_SYNC_EXCLUDES = [
    ".git",
    ".idea",
    "__pycache__",
    "output",
    "logs",
    "*.o",
    "*.d",
    BINARY_NAME,
    "*.skel.h",
    # Configuration is passed as environment variables, which env_loader.c
    # overlays on top of this file; shipping it would only leak whatever
    # OTLP_BEARER_TOKEN the developer has in their checkout.
    ".env",
]

# `make` needs these on the SUT in `source` mode; a missing one otherwise
# surfaces as a wall of compiler noise minutes into a run.
BUILD_TOOLS = ["make", "clang", "gcc", "bpftool"]


