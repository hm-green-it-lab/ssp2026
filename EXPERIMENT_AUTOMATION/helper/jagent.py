def _check_kernel(client: paramiko.SSHClient) -> None:
    """Warn when the SUT kernel lacks BTF, which the agent's CO-RE reads need."""
    code, _, _ = run(client, "test -r /sys/kernel/btf/vmlinux", check=False)
    if code != 0:
        print(
            "[jAgent] WARNING: /sys/kernel/btf/vmlinux is not readable; the agent "
            "needs a BTF-enabled kernel (CONFIG_DEBUG_INFO_BTF)"
        )


def check_usdt_probes(client: paramiko.SSHClient, jvm_lib_path: str) -> None:
    """Verify libjvm.so actually carries the HotSpot USDT probes.

    This is the most likely silent failure in the whole setup: the probes exist
    only if the JDK was configured with ``--enable-dtrace`` at build time. A JVM
    without them starts fine and serves traffic, ``-XX:+DTraceMethodProbes`` is
    accepted, and the agent attaches -- but no transaction is ever detected, so
    the run produces an empty trace that looks like a measurement of nothing.

    Distribution ``openjdk-*-jdk`` packages generally do include them; some
    third-party builds do not, so the JDK must be checked rather than assumed.
    """
    code, out, _ = run(
        client,
        f"readelf -n {shlex.quote(jvm_lib_path)} 2>/dev/null "
        f"| grep -oE 'Name: [A-Za-z_]+' | sed 's/Name: //' | sort -u",
        check=False,
        timeout=120,
    )

    if code != 0 or not out.strip():
        # readelf lives in binutils and may simply be absent on a lean SUT.
        probe_code, _, _ = run(client, "command -v readelf", check=False)
        if probe_code != 0:
            print(
                "[jAgent] WARNING: readelf not available, cannot verify the HotSpot "
                "USDT probes in libjvm.so (install binutils to enable this check)"
            )
            return
        raise RuntimeError(
            f"[jAgent] {jvm_lib_path} carries no SystemTap/USDT probe notes.\n"
            "This JDK was built without --enable-dtrace, so "
            "-XX:+DTraceMethodProbes has nothing to fire and the agent would "
            "record zero transactions.\n"
            "Use a JDK that ships the probes (the distribution's openjdk-*-jdk "
            "package normally does) and point JVM_LIB_PATH at its libjvm.so."
        )

    found = set(out.split())
    required = {"method__entry", "method__return", "object__alloc"}
    missing = required - found
    if missing:
        raise RuntimeError(
            f"[jAgent] {jvm_lib_path} is missing required USDT probes: "
            f"{', '.join(sorted(missing))}.\n"
            f"Probes present: {', '.join(sorted(found)) or '(none)'}\n"
            "Transaction detection needs method__entry/method__return, and the "
            "memory dimension needs object__alloc."
        )
    print(f"[jAgent] libjvm.so provides {len(found)} USDT probes, including all required ones")


def _check_shared_libs(client: paramiko.SSHClient, binary: str) -> None:
    """Fail if the prebuilt binary has unresolved shared libraries.

    The release is dynamically linked against libbpf1, libelf1, zlib1g and
    libcurl4; on a host missing any of them the agent would die at attach time,
    several minutes into a run.
    """
    code, out, _ = run(client, f"ldd {shlex.quote(binary)} 2>&1 || true", check=False)
    missing = [line.strip() for line in out.splitlines() if "not found" in line]
    if missing:
        raise RuntimeError(
            "[jAgent] the prebuilt binary has unresolved libraries on the SUT:\n  "
            + "\n  ".join(missing)
            + "\nInstall them, e.g.:\n"
            "  sudo apt-get install -y libbpf1 libelf1 zlib1g libcurl4"
        )


def _guard_install_dir(config: dict, install_dir: str) -> None:
    """Refuse to wipe an install_dir that also holds the application.

    ``sync_clean`` does ``rm -rf install_dir``. If SUT_BASE_DIR and
    JAGENT_REMOTE_DIR happen to overlap -- both defaulting under
    ``/tmp/ebpf-jagent``, say -- that deletes the spring-rest-service jar and
    the cloned RETIT repository along with the agent, and the next run fails
    with a confusing "jar not found" long after the cause.
    """
    install = install_dir.rstrip("/")
    sut = config.get("sut", {})
    for label, path in (
        ("sut.jar_path", sut.get("jar_path")),
        ("sut.remote_dir", sut.get("remote_dir")),
    ):
        if not path:
            continue
        path = str(path).rstrip("/")
        if path == install or path.startswith(install + "/"):
            raise RuntimeError(
                f"[jAgent] refusing sync_clean: {label} ({path}) lives inside "
                f"jagent.install_dir ({install}), so wiping it would delete the "
                "application as well.\n"
                "Point JAGENT_REMOTE_DIR at a directory outside SUT_BASE_DIR."
            )


def _check_probes_supported(client: paramiko.SSHClient, binary: str) -> None:
    """Fail early if this build predates the ``--probes`` option.

    The published v0.0.1-alpha release does not have it. Passing the flag anyway
    would make the agent exit at attach time -- several minutes into a run --
    and, worse, an agent that silently ignored it would attach the kernel-wide
    probes the setting exists to avoid, quietly invalidating the comparison.
    """
    code, out, err = run(client, f"{shlex.quote(binary)} -h", check=False, timeout=30)
    if "--probes" not in (out + err):
        raise RuntimeError(
            f"[jAgent] jagent.probes is set, but {binary} does not support --probes.\n"
            "The published release predates the option. Either build from source\n"
            "  jagent:\n"
            "    provision: source\n"
            "    source_dir: <checkout with the --probes support>\n"
            "or cut a release containing it and update jagent.release_url."
        )


def _check_min_duration_supported(client: paramiko.SSHClient, binary: str) -> None:
    """Fail early if this build predates ``--min-duration-us``.

    The same failure mode as ``--probes``: getopt refuses the unknown option and
    the agent exits at attach time, several minutes into a run. An agent that
    ignored it silently would be worse. The duration gate is what skips the
    expensive tail of the return handler -- four USDT argument reads, two
    user-memory string copies and the substring match -- so dropping the setting
    would leave that cost in place and the results would attribute it to
    something else.
    """
    code, out, err = run(client, f"{shlex.quote(binary)} -h", check=False, timeout=30)
    if "--min-duration-us" not in (out + err):
        raise RuntimeError(
            f"[jAgent] jagent.min_duration_us is set, but {binary} does not "
            "support --min-duration-us.\n"
            "The option landed in v0.0.4-alpha; an earlier release is pinned. "
            "Either update jagent.release_url or build from source\n"
            "  jagent:\n"
            "    provision: source\n"
            "    source_dir: <checkout with the option>"
        )


def _verify_runs(client: paramiko.SSHClient, binary: str) -> None:
    """Smoke-check the binary by asking for its usage text.

    ``-h`` returns before the agent touches its configuration or the kernel, so
    this validates only that the executable loads on this host.
    """
    code, out, err = run(client, f"{shlex.quote(binary)} -h", check=False, timeout=30)
    combined = (out + err).lower()
    if code != 0 and "usage" not in combined:
        raise RuntimeError(
            f"[jAgent] {binary} is not runnable on the SUT (exit {code}):\n{(out + err).strip()}"
        )


def _provision_noop(client: paramiko.SSHClient, config: dict) -> str:
    """Ship and build the no-op control agent; return the binary path.

    This is the configuration that separates the cost of the USDT probes
    *firing* from the cost of the jAgent's own work: identical probes, empty
    handlers. It is always built from the tree shipped with this automation, so
    it stays in step with the probe set the jAgent attaches to.
    """
    jagent = config.get("jagent", {})
    install_dir = f"{str(jagent['install_dir']).rstrip('/')}-noop"

    source_dir = Path(str(jagent.get("noop_source_dir") or (HERE / "noop_agent")))
    if not (source_dir / "Makefile").exists():
        raise FileNotFoundError(
            f"[jAgent] no-op agent sources not found at {source_dir}"
        )

    # Needs a compiler but not bpftool: the loader opens the object directly
    # rather than going through a generated skeleton.
    # bpftool is needed once, to dump the kernel BTF into vmlinux.h.
    missing = [
        t
        for t in ("make", "clang", "gcc", "bpftool")
        if run(client, f"command -v {t}", check=False)[0] != 0
    ]
    if missing:
        raise RuntimeError(
            f"[jAgent] the SUT cannot build the no-op agent, missing: {', '.join(missing)}.\n"
            "  apt-get install -y make clang gcc bpftool libbpf-dev libelf-dev "
            "zlib1g-dev linux-libc-dev"
        )

    archive = _make_archive(
        source_dir, ["*.o", BINARY_NAME, NOOP_BINARY_NAME, "vmlinux.h", ".build.log"]
    )
    ensure_dir(client, install_dir)
    remote_archive = f"{install_dir}/.noop-src.tar.gz"
    upload(client, archive, remote_archive)
    run(
        client,
        f"tar xzf {shlex.quote(remote_archive)} -C {shlex.quote(install_dir)} "
        f"&& rm -f {shlex.quote(remote_archive)}",
        timeout=300,
    )

    print(f"[jAgent] building the no-op control agent in {install_dir} ...")
    code, out, _ = run(
        client,
        f"cd {shlex.quote(install_dir)} && {{ make clean all; }} > .build.log 2>&1; "
        f"rc=$?; tail -n 25 .build.log; exit $rc",
        check=False,
        timeout=900,
    )
    if out.strip():
        print("    build output (tail):\n" + out.strip())
    if code != 0:
        raise RuntimeError(
            f"[jAgent] no-op agent build failed (exit {code}); "
            f"full log on the SUT at {install_dir}/.build.log"
        )

    binary = _locate_binary(client, install_dir, NOOP_BINARY_NAME)
    run(client, f"chmod +x {shlex.quote(binary)}", check=False)
    _verify_runs(client, binary)
    print(f"[jAgent] no-op control agent ready at {binary}")
    return binary


def _locate_binary(client: paramiko.SSHClient, root: str, name: str = BINARY_NAME) -> str:
    """Find the agent executable under *root*.

    The release archive unpacks into a version-stamped directory
    (``ebpf-jagent-v0.0.1-alpha-linux-x86_64/``), so the path is discovered
    rather than hardcoded and survives a version bump.
    """
    code, out, _ = run(
        client,
        f"find {shlex.quote(root)} -type f -name {shlex.quote(name)} "
        f"-perm -u+x 2>/dev/null | head -n 1",
        check=False,
    )
    if code == 0 and out.strip():
        return out.strip()

    # Fall back to a non-executable match, which the caller then chmods.
    code, out, _ = run(
        client,
        f"find {shlex.quote(root)} -type f -name {shlex.quote(name)} 2>/dev/null | head -n 1",
        check=False,
    )
    if code == 0 and out.strip():
        return out.strip()

    raise FileNotFoundError(f"[jAgent] no '{name}' executable found under {root}")


