# Mode: release
# ──────────────────────────────────────────────────────────────────────────────

def _provision_release(client: paramiko.SSHClient, config: dict, skip_downloads: bool) -> str:
    """Ship and unpack the published release tarball; return the binary path."""
    jagent = config.get("jagent", {})
    install_dir = str(jagent["install_dir"])

    archive = fetch_release_archive(jagent, skip=skip_downloads)

    if jagent.get("sync_clean", False):
        _guard_install_dir(config, install_dir)
        print(f"[jAgent] removing {install_dir} on the SUT (sync_clean) ...")
        run(client, f"rm -rf {shlex.quote(install_dir)}", check=False)

    ensure_dir(client, install_dir)
    remote_archive = f"{install_dir}/{archive.name}"
    upload(client, archive, remote_archive)
    run(
        client,
        f"tar xzf {shlex.quote(remote_archive)} -C {shlex.quote(install_dir)} "
        f"&& rm -f {shlex.quote(remote_archive)}",
        timeout=300,
    )

    binary = _locate_binary(client, install_dir)
    run(client, f"chmod +x {shlex.quote(binary)}", check=False)
    print(f"[jAgent] release unpacked; binary at {binary}")

    _check_shared_libs(client, binary)
    _verify_runs(client, binary)
    return binary


# ──────────────────────────────────────────────────────────────────────────────
# Mode: source
# ──────────────────────────────────────────────────────────────────────────────

def _make_archive(source_dir: Path, excludes: list[str]) -> Path:
    """Pack the agent source tree into a gzipped tar, applying *excludes*.

    A single archive beats per-file SFTP here: the tree carries a ~3 MB
    ``vmlinux.h`` plus many small sources.
    """

    def keep(info: tarfile.TarInfo) -> tarfile.TarInfo | None:
        """Drop excluded members; excluding a directory prunes its contents.

        The prefix is removed with a slice, not ``lstrip("./")`` -- lstrip
        treats its argument as a character set and would turn ``./.git`` into
        ``git``, silently defeating every dotfile exclude.
        """
        name = info.name[2:] if info.name.startswith("./") else info.name
        base = Path(name).name
        for pattern in excludes:
            if fnmatch.fnmatch(base, pattern) or fnmatch.fnmatch(name, pattern):
                return None
        return info

    archive = Path(tempfile.gettempdir()) / "ebpf-jagent-src.tar.gz"
    with tarfile.open(archive, "w:gz") as tar:
        tar.add(str(source_dir), arcname=".", filter=keep)
    print(f"[jAgent] packed source tree ({archive.stat().st_size / 1e6:.1f} MB)")
    return archive


def _check_toolchain(client: paramiko.SSHClient) -> None:
    """Verify the SUT can actually compile the agent."""
    missing = [t for t in BUILD_TOOLS if run(client, f"command -v {t}", check=False)[0] != 0]
    if missing:
        raise RuntimeError(
            f"[jAgent] the SUT is missing build tools: {', '.join(missing)}.\n"
            "Install them, or switch to provision: release.\n"
            "  sudo apt-get install -y make clang llvm gcc libbpf-dev libelf-dev "
            "zlib1g-dev libcurl4-openssl-dev linux-headers-$(uname -r) "
            "linux-tools-$(uname -r)"
        )

    code, _, _ = run(client, "test -d /usr/src/linux-headers-$(uname -r)", check=False)
    if code != 0:
        print(
            "[jAgent] WARNING: /usr/src/linux-headers-$(uname -r) is absent; "
            "the BPF compile may fail"
        )


def _provision_source(client: paramiko.SSHClient, config: dict) -> str:
    """Ship the working tree, build it on the SUT, and return the binary path."""
    jagent = config.get("jagent", {})
    install_dir = str(jagent["install_dir"])

    source = jagent.get("source_dir")
    if not source:
        raise ValueError(
            "provision: source requires jagent.source_dir (set JAGENT_LOCAL_DIR in paths.env)"
        )
    source_dir = Path(str(source)).expanduser()
    if not source_dir.is_dir():
        raise FileNotFoundError(f"[jAgent] source_dir not found on the controller: {source_dir}")
    if not (source_dir / "Makefile").exists():
        raise FileNotFoundError(
            f"[jAgent] {source_dir} does not look like the agent repo (no Makefile)"
        )

    _check_toolchain(client)

    archive = _make_archive(source_dir, list(jagent.get("sync_excludes") or DEFAULT_SYNC_EXCLUDES))

    if jagent.get("sync_clean", False):
        _guard_install_dir(config, install_dir)
        print(f"[jAgent] removing {install_dir} on the SUT (sync_clean) ...")
        run(client, f"rm -rf {shlex.quote(install_dir)}", check=False)

    ensure_dir(client, install_dir)
    remote_archive = f"{install_dir}/.ebpf-jagent-src.tar.gz"
    upload(client, archive, remote_archive)
    run(
        client,
        f"tar xzf {shlex.quote(remote_archive)} -C {shlex.quote(install_dir)} "
        f"&& rm -f {shlex.quote(remote_archive)}",
        timeout=300,
    )
    print(f"[jAgent] source synced to {install_dir}")

    # `make` does not need root here, and root-owned products would complicate
    # a later sync, so sudo is opt-in.
    sudo = privilege_prefix(client) if jagent.get("build_with_sudo", False) else ""
    print(f"[jAgent] building in {install_dir} ...")
    # Output goes to a file and is tailed separately, so the exit code reported
    # back is make's own. Piping make into `tail` would yield tail's status and
    # a failed build would look successful, surfacing later as a confusing
    # "no executable found".
    log = f"{install_dir}/.build.log"
    code, out, _ = run(
        client,
        f"cd {shlex.quote(install_dir)} && {{ {sudo}make clean all; }} "
        f"> {shlex.quote(log)} 2>&1; rc=$?; tail -n 40 {shlex.quote(log)}; exit $rc",
        check=False,
        timeout=1800,
    )
    if out.strip():
        print("[jAgent] build output (tail):\n" + out.strip())
    if code != 0:
        raise RuntimeError(
            f"[jAgent] build failed (exit {code}); full log on the SUT at {log}"
        )

    binary = _locate_binary(client, install_dir)
    _verify_runs(client, binary)
    return binary


