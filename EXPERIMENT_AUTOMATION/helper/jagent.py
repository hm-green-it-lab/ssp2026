# Public API
# ──────────────────────────────────────────────────────────────────────────────

def provision_agent(
    client: paramiko.SSHClient, config: dict, skip_downloads: bool = False
) -> str:
    """Make the agent available on the SUT and return its path.

    Idempotent within one experiment: the work happens on the first call and is
    skipped afterwards, so per-iteration calls are cheap.
    """
    jagent = config.setdefault("jagent", {})
    if jagent.get("__binary__"):
        return str(jagent["__binary__"])

    if not jagent.get("install_dir"):
        raise ValueError("jagent.install_dir is not configured (set JAGENT_REMOTE_DIR in paths.env)")

    mode = str(jagent.get("provision", "release")).lower()
    _check_kernel(client)

    if mode == "release":
        binary = _provision_release(client, config, skip_downloads)
    elif mode == "noop":
        binary = _provision_noop(client, config)
    elif mode == "source":
        binary = _provision_source(client, config)
    elif mode == "preinstalled":
        binary = str(jagent.get("binary") or f"{jagent['install_dir']}/{BINARY_NAME}")
        if not exists(client, binary):
            raise FileNotFoundError(
                f"[jAgent] provision: preinstalled, but no binary at {binary} on the SUT.\n"
                "Use provision: release to download the published build, or "
                "provision: source to ship and compile this checkout."
            )
        _verify_runs(client, binary)
    else:
        raise ValueError(
            f"Unknown jagent.provision: {mode!r} "
            "(expected release, noop, source or preinstalled)"
        )

    jagent["__binary__"] = binary
    return binary


def preflight(client: paramiko.SSHClient, config: dict, skip_downloads: bool = False) -> None:
    """Validate the agent's prerequisites on the SUT before a run starts."""
    jagent = config.get("jagent", {})

    jvm_lib_path = jagent.get("jvm_lib_path")
    if not jvm_lib_path:
        raise ValueError("jagent.jvm_lib_path is not configured (set JVM_LIB_PATH in paths.env)")
    if not exists(client, str(jvm_lib_path)):
        raise FileNotFoundError(
            f"[jAgent] libjvm.so not found on the SUT at {jvm_lib_path}. "
            "It must belong to the JVM that runs the SUT, or the USDT probes "
            "cannot be resolved."
        )
    check_usdt_probes(client, str(jvm_lib_path))

    if not jagent.get("otlp_endpoint"):
        raise ValueError("jagent.otlp_endpoint is not configured; the agent exits without it")

    provision_agent(client, config, skip_downloads=skip_downloads)


def start_agent(
    client: paramiko.SSHClient,
    config: dict,
    target_pid: int,
    remote_dir: str,
    trace_path: str,
    log_path: str,
) -> RemoteProcess:
    """Attach the agent to *target_pid*, writing its trace to *trace_path*.

    The trace file holds the per-transaction records; the log captures libbpf
    attach diagnostics and OTLP export errors.
    """
    jagent = config.get("jagent", {})
    binary = provision_agent(client, config)

    command_parts = [binary, "-p", str(target_pid)]
    method_filter = jagent.get("filter")
    if method_filter:
        command_parts += ["-f", str(method_filter)]

    # Restrict the collected dimensions so the agent attaches the same probes
    # the comparison baseline uses. This is not cosmetic: the network and
    # storage probes hook kernel-wide functions, so leaving them attached makes
    # every socket operation and every write() on the machine trap, which OTJAE
    # never pays for. Requires an agent built from a source tree that supports
    # --probes; see helper/jagent.py::_check_probes_supported.
    probes = jagent.get("probes")
    if probes:
        if isinstance(probes, (list, tuple)):
            probes = ",".join(str(p) for p in probes)
        _check_probes_supported(client, binary)
        command_parts += ["--probes", str(probes)]

    # Suppress emission of calls shorter than this. The gate sits *after* the
    # parent propagation in method_return, so a suppressed call still hands its
    # resources to its caller: this changes what is exported, not what is
    # counted. What it skips is the expensive tail of the return handler -- four
    # USDT argument reads, two copies out of user memory and the substring match
    # against the filter -- which otherwise runs for every one of the tens of
    # thousands of nested JDK calls inside a single transaction.
    #
    # Unlike the kernel-side depth cap this is independent of where in the stack
    # the measured method sits, which is why it, and not the cap, is the knob
    # for keeping deep frames cheap.
    min_duration_us = jagent.get("min_duration_us")
    if min_duration_us:
        _check_min_duration_supported(client, binary)
        command_parts += ["--min-duration-us", str(int(min_duration_us))]

    # The agent always writes a per-transaction line to its output file; there
    # is no flag to suppress it. Pointing it at /dev/null is the only way to
    # avoid the formatting and I/O on the hot path. The data is not lost: the
    # OTLP metrics carry one datapoint per transaction, so differencing the
    # cumulative series reproduces the trace file exactly.
    command_parts.append(trace_path if jagent.get("write_trace", False) else "/dev/null")

    process = RemoteProcess(
        client=client,
        name="jAgent",
        command=f"{privilege_prefix(client)}env "
        + f"JVM_LIB_PATH={shlex.quote(str(jagent['jvm_lib_path']))} "
        + f"OTLP_ENDPOINT={shlex.quote(str(jagent['otlp_endpoint']))} "
        + " ".join(shlex.quote(p) for p in command_parts),
        remote_dir=remote_dir,
        log_path=log_path,
        sudo=True,
    )
    process.start()

    settle = int(jagent.get("attach_settle_secs", 5))
    print(f"[jAgent] waiting {settle}s for probe attachment ...")
    time.sleep(settle)

    if not process.is_running():
        raise RuntimeError(
            f"[jAgent] exited during attachment. Last log lines:\n{process.tail()}"
        )

    # A failed USDT attach is fatal for the measurement, but the agent reports
    # it on stderr and stays alive, so inspect the log explicitly.
    log_text = process.tail(200).lower()
    if "failed to attach" in log_text or "cannot proceed" in log_text:
        raise RuntimeError(
            f"[jAgent] probe attachment failed. Last log lines:\n{process.tail()}"
        )

    print(f"[jAgent] attached to PID {target_pid}, trace -> {trace_path}")
    return process


def stop_agent(process: RemoteProcess, timeout: int = 30) -> None:
    """Stop the agent with SIGINT so it drains its maps and closes the trace."""
    process.stop(timeout=timeout, first_signal="INT")
