# helper/collector.py
"""
OpenTelemetry Collector on the controller.

Both tools under test export OTLP, so the collector is the common point that
makes the comparison fair: OTJAE and the eBPF jAgent go through the same
pipeline instead of one writing logs and the other posting metrics.

It runs on the **controller**, not next to the application. The experiment
measures request latency on the SUT, and the ``eBPF active`` configuration is
already the most CPU-loaded one -- a collector container beside the JVM would
compete for exactly those cycles and perturb the most sensitive configuration
hardest. Both exporters are network clients, so nothing requires locality, and
keeping the collector local also means its output files need no fetching.

Two exporters are fanned out from each pipeline:

``file``
    The data of record: lossless OTLP JSON, one line per batch, every point that
    arrives. No scrape quantisation, no polling.
``prometheus``
    Scraped by the http-logger, matching the other experiment. Both tools emit
    *cumulative* sums, so a sampled series is what allows the steady-state
    window to be isolated from ramp-up and ramp-down.

``debug`` is enabled at ``basic`` verbosity as a sanity check only -- it is a
human-readable dump, not a stable format, and in current collector versions it
is what the old ``logging`` exporter was renamed to.

Both the ``file`` and ``prometheus`` exporters live in the *contrib*
distribution, so the core collector image will not do.
"""

from __future__ import annotations

import shutil
import socket
import subprocess
import time
from pathlib import Path

from helper.local_proc import LocalProcess

CONTAINER_NAME = "ssp-otel-collector"

CONFIG_TEMPLATE = """\
# Generated by EXPERIMENT_AUTOMATION -- do not edit by hand.
receivers:
  otlp:
    protocols:
      http:
        endpoint: 0.0.0.0:{otlp_port}
      grpc:
        endpoint: 0.0.0.0:{grpc_port}

processors:
  batch:
    timeout: {batch_timeout}

exporters:
  file:
    path: {file_path}
  prometheus:
    endpoint: 0.0.0.0:{prometheus_port}
    resource_to_telemetry_conversion:
      enabled: true
  debug:
    verbosity: basic

service:
  pipelines:
    metrics:
      receivers: [otlp]
      processors: [batch]
      exporters: [file, prometheus, debug]
    traces:
      receivers: [otlp]
      processors: [batch]
      exporters: [file, debug]
"""


def controller_address(collector_config: dict, sut_host: str) -> str:
    """Return the controller address the SUT should export to.

    Auto-detected by opening a socket toward the SUT and reading back the local
    endpoint, which yields the controller's address on the interface that
    actually routes there -- more reliable than guessing among several NICs.
    ``collector.controller_host`` overrides it.
    """
    override = collector_config.get("controller_host")
    if override:
        return str(override)

    probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        # UDP connect performs no traffic; it only selects a route.
        probe.connect((sut_host, 9))
        return probe.getsockname()[0]
    except OSError as exc:
        raise RuntimeError(
            f"Could not determine the controller address toward {sut_host}: {exc}. "
            "Set collector.controller_host explicitly."
        ) from exc
    finally:
        probe.close()


def otlp_endpoint(collector_config: dict, sut_host: str, path: str = "") -> str:
    """Build the OTLP/HTTP URL the SUT-side exporters should post to."""
    host = controller_address(collector_config, sut_host)
    port = int(collector_config.get("otlp_http_port", 4318))
    return f"http://{host}:{port}{path}"


def prometheus_url(collector_config: dict) -> str:
    """Local Prometheus exposition URL, scraped by the http-logger."""
    port = int(collector_config.get("prometheus_port", 8889))
    # "localhost", not "127.0.0.1": podman on Windows forwards published ports
    # to the IPv6 loopback, so the IPv4 literal is refused while the name
    # resolves to both families.
    return f"http://localhost:{port}/metrics"


def sut_can_reach(client, endpoint: str) -> bool:
    """Probe from the SUT whether the collector's OTLP endpoint is reachable.

    Any HTTP status counts as success -- a 400 from posting an empty body still
    proves the port answered. Only a transport failure means unreachable.
    """
    from helper.ssh import run  # imported here to avoid a circular import

    code, out, _ = run(
        client,
        f"curl -s -o /dev/null -w '%{{http_code}}' --max-time 8 -X POST "
        f"-H 'Content-Type: application/json' -d '{{}}' {endpoint}/v1/metrics || echo 000",
        check=False,
        timeout=30,
    )
    status = out.strip()[-3:]
    return code == 0 and status.isdigit() and status != "000"


def resolve_endpoint(client, collector_config: dict, sut_host: str):
    """Decide how the SUT should reach the collector; return (endpoint, tunnel).

    ``collector.tunnel``:

    ``auto`` (default)
        Try the controller's LAN address first and fall back to a reverse SSH
        forward. Self-configuring, and the log records which path was taken.
    ``always``
        Skip the probe and tunnel unconditionally.
    ``never``
        Require the direct path, and fail loudly if the SUT cannot reach it.
    """
    from helper.tunnel import ReverseTunnel

    mode = str(collector_config.get("tunnel", "auto")).lower()
    if mode not in {"auto", "always", "never"}:
        raise ValueError(f"Unknown collector.tunnel: {mode!r} (expected auto, always or never)")

    port = int(collector_config.get("otlp_http_port", 4318))
    direct = otlp_endpoint(collector_config, sut_host)

    if mode != "always":
        if sut_can_reach(client, direct):
            print(f"[Collector] SUT reaches the collector directly at {direct}")
            return direct, None
        if mode == "never":
            raise RuntimeError(
                f"[Collector] the SUT cannot reach {direct} and collector.tunnel is "
                "'never'.\nEither open the path, or set collector.tunnel: auto."
            )
        print(f"[Collector] SUT cannot reach {direct}; falling back to an SSH tunnel")

    tunnel = ReverseTunnel(client, remote_port=port, local_port=port)
    tunnel.start()
    tunnelled = f"http://127.0.0.1:{port}"

    if not sut_can_reach(client, tunnelled):
        tunnel.stop()
        raise RuntimeError(
            f"[Collector] the tunnel is up but the SUT still cannot reach {tunnelled}. "
            "Check that the collector is running and that sshd permits forwarding."
        )
    print(f"[Collector] SUT reaches the collector through the tunnel at {tunnelled}")
    return tunnelled, tunnel


def render_config(collector_config: dict, config_path: Path, file_output: Path) -> Path:
    """Write the collector configuration for this run."""
    config_path.parent.mkdir(parents=True, exist_ok=True)
    rendered = CONFIG_TEMPLATE.format(
        otlp_port=int(collector_config.get("otlp_http_port", 4318)),
        grpc_port=int(collector_config.get("otlp_grpc_port", 4317)),
        prometheus_port=int(collector_config.get("prometheus_port", 8889)),
        batch_timeout=str(collector_config.get("batch_timeout", "5s")),
        # Inside the container the output directory is mounted at /out.
        file_path=(
            f"/out/{file_output.name}"
            if str(collector_config.get("mode", "container")).lower() == "container"
            else file_output.as_posix()
        ),
    )
    config_path.write_text(rendered, encoding="utf-8")
    return config_path


class Collector:
    """Lifecycle of one collector instance, container- or binary-backed."""

    def __init__(self, collector_config: dict, config_path: Path, output_dir: Path, log_path: Path):
        self.config = collector_config
        self.mode = str(collector_config.get("mode", "container")).lower()
        self.config_path = config_path
        self.output_dir = output_dir
        self.log_path = log_path
        self.process: LocalProcess | None = None
        self._container_started = False

    # ── container backend ────────────────────────────────────────────────────

    def _runtime(self) -> str:
        """Resolve the container runtime executable.

        ``auto`` (the default) picks the first of docker/podman actually present,
        so a controller with only one of them needs no configuration. An explicit
        value is honoured as given, which is what a reproducible campaign wants.
        """
        configured = str(self.config.get("container_runtime", "auto")).lower()

        if configured != "auto":
            if shutil.which(configured) is None:
                alternatives = [r for r in ("docker", "podman") if shutil.which(r)]
                hint = (
                    f" {alternatives[0]!r} is available — set "
                    f"collector.container_runtime: {alternatives[0]}."
                    if alternatives
                    else ""
                )
                raise RuntimeError(
                    f"[Collector] container runtime {configured!r} not found on the "
                    f"controller.{hint}\n"
                    "Alternatives:\n"
                    "  - collector.mode: binary  + collector.binary: <otelcol-contrib path>\n"
                    "  - collector.enabled: false (no telemetry is collected at all)"
                )
            return configured

        for candidate in ("docker", "podman"):
            if shutil.which(candidate):
                return candidate

        raise RuntimeError(
            "[Collector] no container runtime found on the controller (looked for "
            "docker and podman).\n"
            "Alternatives:\n"
            "  - install Docker Desktop or Podman\n"
            "  - collector.mode: binary  + collector.binary: <otelcol-contrib path>\n"
            "  - collector.enabled: false (no telemetry is collected at all)"
        )

    def _start_container(self) -> None:
        runtime = self._runtime()
        print(f"[Collector] using container runtime: {runtime}")
        image = str(self.config.get("image", "otel/opentelemetry-collector-contrib:latest"))
        otlp_http = int(self.config.get("otlp_http_port", 4318))
        otlp_grpc = int(self.config.get("otlp_grpc_port", 4317))
        prom = int(self.config.get("prometheus_port", 8889))

        # Remove a leftover from an interrupted run before binding the ports.
        try:
            subprocess.run([runtime, "rm", "-f", CONTAINER_NAME], capture_output=True, text=True)
        except OSError:
            pass

        command = [
            runtime, "run", "-d", "--name", CONTAINER_NAME,
            "-p", f"{otlp_http}:{otlp_http}",
            "-p", f"{otlp_grpc}:{otlp_grpc}",
            "-p", f"{prom}:{prom}",
            # as_posix() yields forward slashes, which both docker and podman
            # parse correctly as a Windows host path in a -v argument.
            "-v", f"{self.config_path.resolve().as_posix()}:/etc/otelcol-contrib/config.yaml:ro",
            "-v", f"{self.output_dir.resolve().as_posix()}:/out",
            image,
            "--config", "/etc/otelcol-contrib/config.yaml",
        ]
        print(f"[Collector] $ {' '.join(command)}")
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            hint = (
                "On Windows podman needs its VM running: `podman machine start`.\n"
                if runtime == "podman"
                else "Is the Docker daemon running?\n"
            )
            raise RuntimeError(
                f"[Collector] failed to start container:\n{result.stderr.strip()}\n"
                + hint
                + "Or set collector.mode: binary to use an otelcol-contrib executable."
            )
        self._container_started = True
        print(f"[Collector] container {CONTAINER_NAME} started")

    def _stop_container(self) -> None:
        runtime = self._runtime()
        # Capture the collector's own log before discarding the container.
        logs = subprocess.run(
            [runtime, "logs", CONTAINER_NAME], capture_output=True, text=True
        )
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.log_path.write_text(
            (logs.stdout or "") + (logs.stderr or ""), encoding="utf-8", errors="replace"
        )
        # SIGTERM first so the batch processor flushes to the file exporter.
        subprocess.run([runtime, "stop", "-t", "10", CONTAINER_NAME], capture_output=True, text=True)
        subprocess.run([runtime, "rm", "-f", CONTAINER_NAME], capture_output=True, text=True)
        print(f"[Collector] container stopped; log -> {self.log_path}")

    # ── binary backend ───────────────────────────────────────────────────────

    def _start_binary(self) -> None:
        binary = self.config.get("binary")
        if not binary:
            raise ValueError("collector.mode: binary requires collector.binary")
        if not Path(str(binary)).expanduser().exists():
            raise FileNotFoundError(f"[Collector] otelcol-contrib not found at {binary}")

        self.process = LocalProcess(
            name="Collector",
            command=[str(binary), "--config", str(self.config_path)],
            log_path=self.log_path,
        )
        self.process.start()

    # ── public API ───────────────────────────────────────────────────────────

    def start(self) -> None:
        """Launch the collector and wait until its OTLP port accepts connections."""
        self.output_dir.mkdir(parents=True, exist_ok=True)
        if self.mode == "container":
            self._start_container()
        elif self.mode == "binary":
            self._start_binary()
        else:
            raise ValueError(
                f"Unknown collector.mode: {self.mode!r} (expected container or binary)"
            )
        self._wait_ready()

    def _wait_ready(self, timeout: int = 60) -> None:
        """Block until the OTLP HTTP port is listening."""
        port = int(self.config.get("otlp_http_port", 4318))
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                # A hostname rather than an IPv4 literal: create_connection
                # walks every getaddrinfo result, so this succeeds whether the
                # runtime published to 127.0.0.1 or ::1. Podman on Windows uses
                # the latter, which made the IPv4-only probe fail against a
                # collector that was in fact running.
                with socket.create_connection(("localhost", port), timeout=2):
                    print(f"[Collector] ready on :{port}")
                    return
            except OSError:
                if self.process and not self.process.is_running():
                    raise RuntimeError(
                        f"[Collector] exited during startup:\n{self.process.tail()}"
                    )
                time.sleep(1)
        raise TimeoutError(f"[Collector] OTLP port {port} not listening within {timeout}s")

    def stop(self) -> None:
        """Stop the collector, giving the batch processor time to flush."""
        if self.mode == "container" and self._container_started:
            self._stop_container()
        elif self.process:
            # SIGTERM/graceful first so buffered batches reach the file exporter.
            self.process.stop(timeout=20)

    def firewall_hint(self, sut_host: str) -> str:
        """One-line reminder that the SUT must be able to reach these ports."""
        host = controller_address(self.config, sut_host)
        ports = (
            int(self.config.get("otlp_http_port", 4318)),
            int(self.config.get("otlp_grpc_port", 4317)),
        )
        return (
            f"the SUT must reach {host} on {ports[0]}/{ports[1]} "
            "(a host firewall on the controller will silently drop the exports)"
        )
